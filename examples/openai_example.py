"""
OpenAI Function Calling Integration with CrossX Security Gateway (Section 19).
Demonstrates:
1. Wrapping OpenAI client/tools with CrossXOpenAIProxy.
2. Intercepting tool_calls generated by OpenAI models before external dispatch.
3. Allowing legitimate calls and filtering out adversarial calls (/etc/shadow).
"""

from crossx import CrossXClient, CrossXBlockedError
from crossx.adapters import CrossXOpenAIProxy


def main():
    crossx = CrossXClient(
        endpoint="http://localhost:8000",
        api_key="agk_live_test_key_sample"
    )

    proxy = CrossXOpenAIProxy(client=crossx)

    print("OpenAI Tool Call Interceptor configured.")

    # 1. Permitted function call
    safe_call = {
        "id": "call_safe_001",
        "type": "function",
        "function": {
            "name": "filesystem_tool",
            "arguments": '{"operation": "read_file", "resource": "public/data.json"}'
        }
    }
    safe_eval = proxy.validate_tool_call(safe_call)
    print("Safe OpenAI function call verified:", safe_eval.get("decision", "ALLOWED"))

    # 2. Blocked malicious function call
    malicious_call = {
        "id": "call_exploit_002",
        "type": "function",
        "function": {
            "name": "filesystem_tool",
            "arguments": '{"operation": "read_file", "resource": "/etc/shadow"}'
        }
    }
    try:
        print("\nAttempting unauthorized function call targeting '/etc/shadow'...")
        proxy.validate_tool_call(malicious_call)
        print("WARNING: Function call was not blocked!")
    except CrossXBlockedError as e:
        print("SUCCESS: Function call BLOCKED by CrossX Proxy!")
        print("Reason:", e.message)


if __name__ == "__main__":
    main()
