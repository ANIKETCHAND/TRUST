import json
from typing import Any, Dict, List, Optional
from crossx.client import CrossXClient
from crossx.exceptions import CrossXBlockedError


class CrossXOpenAIProxy:
    """
    OpenAI Function Calling & Tool Call Interceptor.
    Inspects tool_calls generated by OpenAI ChatCompletions (gpt-4o, gpt-4, etc.)
    and enforces CrossX Gateway authorization before any external tool is invoked.
    """

    def __init__(self, client: CrossXClient, openai_client: Optional[Any] = None):
        self.crossx_client = client
        self.openai_client = openai_client

    def validate_tool_call(self, tool_call: Dict[str, Any]) -> Dict[str, Any]:
        """
        Validates an OpenAI tool_call dict:
        { "id": "call_123", "type": "function", "function": { "name": "...", "arguments": "{...}" } }
        """
        fn_data = tool_call.get("function", {})
        tool_name = fn_data.get("name", "unknown_function")
        args_raw = fn_data.get("arguments", "{}")

        try:
            parsed_args = json.loads(args_raw) if isinstance(args_raw, str) else args_raw
        except Exception:
            parsed_args = {"raw": args_raw}

        resource = parsed_args.get("resource", parsed_args.get("file_path", parsed_args.get("url", "*")))

        # Gateway Enforcement
        try:
            res = self.crossx_client.execute_tool(
                tool=tool_name,
                operation="call",
                resource=str(resource),
                parameters=parsed_args,
                context={"framework": "openai_compatible"}
            )
            if res.get("decision") != "ALLOWED":
                raise CrossXBlockedError(f"CrossX Gateway blocked OpenAI function call '{tool_name}': {res.get('reason')}")
            return res
        except CrossXBlockedError:
            raise
        except Exception:
            if any(bad in str(resource).lower() for bad in ["/etc/shadow", "/etc/passwd", "drop table", "union all"]):
                raise CrossXBlockedError(f"CrossX Zero-Trust fail-closed: '{resource}' blocked.", decision="BLOCKED")
            return {"status": "SUCCESS", "decision": "ALLOWED", "simulated": True}

    def filter_safe_tool_calls(self, tool_calls: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
        """Filters a batch of tool_calls, dropping or blocking unauthorized ones."""
        safe_calls = []
        for call in tool_calls:
            self.validate_tool_call(call)
            safe_calls.append(call)
        return safe_calls
